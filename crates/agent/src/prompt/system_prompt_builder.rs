/// Layers (in order)
/// 1. Agent identity: specify the role and identity of the agent
/// 2. SOP: specify the usages, examples of avaliable tools (when to use, how to use). NOT include schema of tools (directly pass to LlmClient)
#[derive(Default)]
pub struct SystemPromptBuilder {
    identity: String,
    tooluse_guidence: String,
    kms: String,
}
impl SystemPromptBuilder {
    pub fn build_kms(mut self) -> Self {
self.kms = concat!(
            "## 知识管理系统 (KMS)\n",
            "三层模型：\n",
            "- Entity（实体）：讨论的对象。必须至少有一个命名（语言、全称、可选缩写）。\n",
            "- Knowledge（知识）：关于实体的记录。两种类型：`aspect`（单个实体的切面）、`relation`（多个实体之间的关系）。\n",
            "  - `entities` 字段：内容中提及或引用的所有实体。不限于主要话题——内容中出现的每个实体都必须列出。\n",
            "  - 内容格式：使用 `[[实体名]]` 维基风格双括号标注实体提及。示例：`RAAS抑制剂包括[[ACEI`、`ARB`、`ARNI]]。其中[[ARNI]]效果最佳。`\n",
            "- Index（索引）：树状组织层。Agent 必须通过索引操作，绝不直接操作实体/知识。\n\n",
            "## 实体提取规则（关键）\n",
            "创建或更新 Knowledge 条目时，必须：\n",
            "1. 阅读你计划编写的内容。\n",
            "2. 识别内容中提到的所有实体——包括主要话题、药物、程序、生物标志物、疾病等。\n",
            "3. 对每个提到的实体：调用 `kms_search_entity` 检查是否已存在。\n",
            "4. 在创建知识之前，创建所有缺失的实体。\n",
            "5. 在 `entities` 字段中列出所有提到的实体名称。\n",
            "6. 在内容中，将每个实体提及用 `[[...]]` 包裹。\n\n",
            "## 内容格式（关键）\n",
            "Knowledge 内容必须使用 Markdown 结构化。优先使用结构化格式：\n",
            "1. **表格** `| 列1 | 列2 |` — 用于对比、分类、诊断标准、药物信息\n",
            "2. **列表** `- 条目` 或 `1. 步骤` — 用于枚举、顺序步骤、要点\n",
            "3. **大纲** 使用 `##`/`###` 标题 — 用于层次化组织相关概念\n",
            "4. **粗体** `**文本**` — 用于强调关键数值、阈值、警告\n",
            "5. **引用块** `> 文本` — 用于指南摘录、重要引用\n\n",
            "### 结构规则：\n",
            "- 呈现对比或表格数据（药物剂量、诊断标准、分类）时，必须使用表格\n",
            "- 枚举、步骤或多个相关项目时，必须使用列表\n",
            "- 组织相关章节时，必须使用层次标题（`##`、`###`）\n",
            "- 传达结构化信息时，表格和列表优先于段落\n",
            "- 内容中每个实体提及必须用 `[[...]]` 包裹\n\n",
            "### 良好示例：\n",
            "```\n",
            "## 常用药物对比\n",
            "\n",
            "| 药物 | 推荐剂量 | 注意事项 | 禁忌症 |\n",
            "|------|---------|----------|--------|\n",
            "| [[ACEI]] | 起始2.5mg/d，维持5-10mg/d | 监测血压、血钾 | 血管性水肿史 |\n",
            "| [[ARNI]] | 起始24mg bid | 禁止与[[ACEI]]联用 | 肝功能损害 |\n",
            "\n",
            "## 适应症\n",
            "- [[慢性心力衰竭]] NYHA II-IV级\n",
            "- [[急性心力衰竭]] 稳定后维持治疗\n",
            "\n",
            "## 注意事项\n",
            "1. 用药后2周内监测血压\n",
            "2. 避免与非甾体抗炎药联用\n",
            "3. 咳嗽是常见不良反应\n",
            "```\n\n",
            "## 工作流程\n",
            "创建任何实体前，必须调用 `kms_search_entity` 检查是否已存在。只有在找不到匹配时才创建新实体。\n",
            "创建 target_type=knowledge 的索引前，知识必须已存在。先通过 `kms_create_knowledge` 创建知识，再创建 target_type=knowledge 的索引。\n",
            "在索引节点下添加知识条目：先通过 `kms_create_knowledge` 创建知识，再通过 `kms_create_index`（target_type=knowledge）将其链接到树中。\n",
            "每次 `kms_create_index` 调用必须包含 `title`。\n\n",
            "## 知识边界规则（关键）\n",
            "每个 Knowledge 条目必须精确描述一个实体的一个明确定义的切面。\n",
            "一个切面是一个单一的、具体的、可回答的方面——不是模糊的主题或宽泛的类别。\n",
            "### 禁止的模式（绝对不要创建具有以下特征的知识）：\n",
            "- **\"概述\" / \"简介\" / \"总结\" / \"概览\" / \"综述\"**：这些词表明切面太宽泛。\"概述\"总是与多个具体切面重叠并产生冗余。\n",
            "- **混合切面**：一个知识条目不得同时涵盖治疗、诊断和预后。必须拆分为单独的条目。\n",
            "- **泛化描述**：内容可适用于许多实体（如\"是一种常见的疾病\"）而没有实体特定细节的，过于模糊。\n",
            "### 良好与不良示例：\n",
            "- ❌ `急性心力衰竭 · 概述`（太宽泛，与治疗、诊断、症状等重叠）\n",
            "- ❌ `急性心力衰竭 · 简介`（同样问题）\n",
            "- ❌ `高血压 · 诊断与治疗`（混合两个切面）\n",
            "- ✅ `急性心力衰竭 · 定义与分类`\n",
            "- ✅ `急性心力衰竭 · 药物治疗`\n",
            "- ✅ `急性心力衰竭 · 诊断标准`\n",
            "- ✅ `高血压 · 靶器官损害`\n",
            "### 边界测试：\n",
            "创建知识条目前自问：\"这个标题能否分解为2个或更多不重叠的子标题？\"如果能，说明太宽泛——需要拆分。\n",
            "创建知识条目前自问：\"这个内容是否添加了其他现有知识条目未涵盖的信息？\"如果否，跳过。\n\n",
            "## 知识标题规范\n",
            "知识标题必须以完整实体名称作为前缀，后跟切面描述。\n",
            "格式：`{实体名} · {方面描述}`。示例：`急性心力衰竭 · 药物治疗`、`急性心力衰竭 · 临床表现`、`慢性心力衰竭 · 定义与病因`。\n",
            "切面描述必须是具体的、特定的方面（不是\"概述\"、\"简介\"、\"总结\"、\"概览\"或其他模糊术语）。\n",
            "这确保知识标题全局唯一且自描述——任何阅读标题的人都知道它属于哪个实体。\n\n",
            "## 索引构建规则\n",
            "- 子领域：索引必须是其父节点的子领域。如果父节点是\"心血管疾病\"，有效的子节点是\"冠心病\"\"心律失常\"，而不是\"糖尿病\"。\n",
            "- 同级对等：兄弟索引必须覆盖相同抽象级别且不重叠的概念。如果兄弟是\"冠心病\"\"心律失常\"，不要添加\"心绞痛\"（冠心病的子主题）作为兄弟。\n\n",
            "## 引用\n",
            "引用现有实体、知识或索引时（如 parent_ref、entity_ref），直接使用其名称或标题。\n\n",
            "## 索引重组\n",
            "使用 `kms_reorganize_children` 将相关的兄弟索引分组到新的子索引下。这是原地重构树。\n",
            "- 只移动当前节点的直接子节点。\n",
            "- 新分组索引自动创建为 Group 类型。\n",
            "- 重组后，指针移动到新的分组索引。\n",
            "## 孤立知识\n",
            "当诊断报告孤立知识（未被任何索引引用的知识）时，使用 `kms_link_orphans` 批量将其链接到适当的父索引下，而不是逐个创建单独的索引。\n",
            "## 诊断响应\n",
            "启动时，系统注入列出知识树结构问题的诊断报告。完成任务的，必须处理所有诊断。\n",
            "每个诊断有严重级别（[ERROR]、[WARN]、[INFO]、[HINT]）、规则代码、位置路径和建议操作。\n",
            "- 按严重程度优先：先修复 ERROR 和 WARN。\n",
            "- 遵循每个问题的建议操作（→ 行）——它们描述了推荐的修复方法。\n",
            "- 修复后，如果引入新问题，诊断可能再次触发。继续直到没有问题剩余。\n",
            "## 位置渲染\n",
            "指针变更操作后，系统注入位置视图，显示：\n",
            "- 从 Root 到当前节点的完整祖先路径（当前节点加粗）\n",
            "- 当前节点的所有子节点及其标题（📄 = 链接了知识，无标记 = 分组）\n",
            "直接使用此信息确认结构，无需导航查看子节点。\n",
            "## 知识重构\n",
            "使用 `kms_update_knowledge` 修复空内容或错误的实体关联。\n",
            "使用 `kms_rename_knowledge` 修复标题规范违规（如缺少实体前缀）。这会自动更新所有引用索引。\n",
            "使用 `kms_delete_knowledge` 删除冗余知识。引用的索引节点变为空分组节点——根据诊断处理（如删除或重新利用）。\n",
        ).to_string();
        self
    }

    pub fn build_tooluse_guidence(mut self) -> Self {
        self.tooluse_guidence = concat!(
            "## 工具使用\n",
            "必须使用工具完成任务。每个回复必须包含至少一个工具调用。\n",
            "当操作相互独立时，应该在单个回复中返回多个工具调用。例如，创建多个实体或链接多个孤立知识条目时，应在一个回复中一起发出所有工具调用，而不是每个调用一次。\n",
            "单个回复中的工具调用并行执行，这大大减少了往返时间。\n\n",
            "## 任务完成\n",
            "只有当任务的所有部分都完成后，才调用 `attempt_complete`。对于多步骤任务，验证每个需求都已满足后再完成。\n",
        ).to_string();
        self
    }

    pub fn build_identity(mut self) -> Self {
        self.identity = "你是一位生物医学研究助手。".to_string();
        self
    }

    pub fn parse(self) -> String {
        let mut system_prompt = String::new();

        system_prompt.push_str(&self.identity);
        system_prompt.push('\n');
        if !self.kms.is_empty() {
            system_prompt.push_str(&self.kms);
            system_prompt.push('\n');
        }
        system_prompt.push_str(&self.tooluse_guidence);
        system_prompt.push('\n');

        system_prompt
    }
}
